# Generates symbols.idx (full symbol index) and the AUTO block inside AI_GUIDE.md. Run via build.py. Pure stdlib.
import re, glob, os, datetime
def _logical_files():
    """name -> (list of (partfile, text)) so line numbers can be reported both logically and per part."""
    out = {}
    out['srcA'] = [('parts/srcA.html', open('parts/srcA.html', encoding='utf-8').read())]
    out['srcB'] = [(p, open(p, encoding='utf-8').read()) for p in sorted(glob.glob('parts/srcB_*.part'))]
    out['srcN'] = [('parts/srcN.html', open('parts/srcN.html', encoding='utf-8').read())]
    out['srcDev'] = [('parts/srcDev.html', open('parts/srcDev.html', encoding='utf-8').read())]
    out['locpicker'] = [('parts/locpicker.js', open('parts/locpicker.js', encoding='utf-8').read())]
    out['export_addon'] = [('parts/export_addon.js', open('parts/export_addon.js', encoding='utf-8').read())]
    return out
def _where(name, parts, lineno):
    if len(parts) == 1: return f"{parts[0][0]}:{lineno}"
    acc = 0
    for p, t in parts:
        n = t.count('\n') + (0 if t.endswith('\n') else 1)
        if lineno <= acc + n: return f"{p}:{lineno-acc}"
        acc += n
    return f"{parts[-1][0]}:{lineno}"
RE_FN = re.compile(r'^ {0,4}(?:async\s+)?function\s+([A-Za-z_$][\w$]*)')
RE_WIN = re.compile(r'^\s{0,4}window\.([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?function')
RE_CONST = re.compile(r'^(?:const|let|var)\s+([A-Z][A-Z0-9_]{2,})\s*=')
RE_ID = re.compile(r'id="((?:panel|tab)-[\w-]+)"')
def gen_guide():
    files = _logical_files(); idx = []; banners = {}; sizes = []
    for name, parts in files.items():
        text = ''.join(t for _, t in parts); lines = text.split('\n')
        sizes.append((name, len(lines), sum(len(t.encode()) for _, t in parts)//1024, ', '.join(os.path.basename(p) for p, _ in parts)))
        bl = []
        for i, l in enumerate(lines, 1):
            m = RE_FN.match(l) or RE_WIN.match(l)
            if m: idx.append((m.group(1), 'fn', _where(name, parts, i), name)); continue
            m = RE_CONST.match(l)
            if m: idx.append((m.group(1), 'const', _where(name, parts, i), name)); continue
            for m in RE_ID.finditer(l): idx.append((m.group(1), 'id', _where(name, parts, i), name))
            if re.match(r'^\s*/\*\s*={6,}', l):
                j = i
                while j < len(lines) and not re.search(r'[A-Za-z]{3}', re.sub(r'[=\-*/]', '', lines[j])): j += 1
                if j < len(lines):
                    t = re.sub(r'[=*/]+', ' ', lines[j]).strip(' -')
                    t = re.sub(r'\s+', ' ', t)[:90]
                    if t and not re.search(r'[{};=]', t) and (not bl or bl[-1][1] != t): bl.append((i, t))
        banners[name] = bl
    with open('symbols.idx', 'w', encoding='utf-8') as f:
        f.write('# AUTO-GENERATED by build.py - do not edit. Format: name<TAB>kind<TAB>file:line<TAB>app\n# Use: grep -n "^computeFate" symbols.idx   (never read this file whole)\n')
        for n, k, w, a in sorted(idx, key=lambda r: r[0].lower()): f.write(f"{n}\t{k}\t{w}\t{a}\n")
    auto = ['<!-- AUTO:START (rewritten by build.py on every build; do not edit by hand) -->',
            f'_Generated {datetime.date.today().isoformat()} - {len(idx)} symbols in `symbols.idx`._', '',
            '### File sizes (read only what you need)', '| App | Lines | KB | Files |', '|---|---|---|---|']
    for n, ln, kb, fl in sizes: auto.append(f'| {n} | {ln} | {kb} | {fl} |')
    auto += ['', '### Section map (banner titles, logical line numbers - use `Read` with offset/limit)']
    for name in ('srcB', 'srcA', 'srcN', 'locpicker', 'export_addon'):
        if not banners.get(name): continue
        auto.append(f'**{name}**'); parts = files[name]
        auto.append('; '.join(f'{t} @{_where(name, parts, ln).split("/")[-1]}' for ln, t in banners[name]))
        auto.append('')
    auto.append('<!-- AUTO:END -->')
    block = '\n'.join(auto)
    g = open('AI_GUIDE.md', encoding='utf-8').read() if os.path.exists('AI_GUIDE.md') else '<!-- AUTO:START -->\n<!-- AUTO:END -->\n'
    g = re.sub(r'<!-- AUTO:START.*?<!-- AUTO:END -->', lambda m: block, g, flags=re.S)
    open('AI_GUIDE.md', 'w', encoding='utf-8').write(g)
    print('guide: %d symbols' % len(idx))
