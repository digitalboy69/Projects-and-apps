# Generates symbols.idx (full symbol index) and the AUTO block inside AI_GUIDE.md. Run via build.py. Pure stdlib.
import datetime, glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RE_FN = re.compile(r'^ {0,4}(?:async\s+)?function\s+([A-Za-z_$][\w$]*)')
RE_WIN = re.compile(r'^\s{0,4}window\.([A-Za-z_$][\w$]*)\s*=\s*(?:async\s+)?function')
RE_CONST = re.compile(r'^(?:const|let|var)\s+([A-Z][A-Z0-9_]{2,})\s*=')
RE_ID = re.compile(r'id="((?:panel|tab)-[\w-]+)"')


def source_files():
    """[(app_label, relative_path)] for every hand-written code file worth indexing."""
    out = []
    for d in sorted(glob.glob(os.path.join(ROOT, 'apps', '*'))):
        app = os.path.basename(d)
        out.append((app, f'apps/{app}/index.html'))
        out += [(app, os.path.relpath(p, ROOT)) for p in sorted(glob.glob(os.path.join(d, 'js', '*.js')))]
        out += [(app, os.path.relpath(p, ROOT)) for p in sorted(glob.glob(os.path.join(d, 'css', '*.css')))]
    out += [('shell', 'index.html')]
    out += [('shell', os.path.relpath(p, ROOT)) for p in sorted(glob.glob(os.path.join(ROOT, 'shell', '*', '*')))]
    out += [('shared', os.path.relpath(p, ROOT)) for p in sorted(glob.glob(os.path.join(ROOT, 'shared', '*')))]
    return out


def gen_guide():
    idx, rows = [], {}
    for app, rel in source_files():
        text = open(os.path.join(ROOT, rel), encoding='utf-8').read(); lines = text.split('\n')
        rows.setdefault(app, []).append((rel, len(lines), len(text.encode()) // 1024))
        if not rel.endswith(('.js', '.html')): continue
        for i, l in enumerate(lines, 1):
            m = RE_FN.match(l) or RE_WIN.match(l)
            if m: idx.append((m.group(1), 'fn', f'{rel}:{i}', app)); continue
            m = RE_CONST.match(l)
            if m: idx.append((m.group(1), 'const', f'{rel}:{i}', app)); continue
            for m in RE_ID.finditer(l): idx.append((m.group(1), 'id', f'{rel}:{i}', app))
    with open(os.path.join(ROOT, 'symbols.idx'), 'w', encoding='utf-8') as f:
        f.write('# AUTO-GENERATED by build.py - do not edit. Format: name<TAB>kind<TAB>file:line<TAB>app\n# Use: grep -n "^computeFate" symbols.idx   (never read this file whole)\n')
        for n, k, w, a in sorted(idx, key=lambda r: r[0].lower()): f.write(f'{n}\t{k}\t{w}\t{a}\n')
    auto = ['<!-- AUTO:START (rewritten by build.py on every build; do not edit by hand) -->',
            f'_Generated {datetime.date.today().isoformat()} - {len(idx)} symbols in `symbols.idx` (paths are real files now: `Read` them with offset/limit)._', '',
            '### File map (lines / KB) - file names say what is inside']
    for app, items in rows.items():
        tot_l = sum(r[1] for r in items); tot_k = sum(r[2] for r in items)
        auto += ['', f'**{app}** - {len(items)} files, {tot_l} lines, {tot_k} KB', '```']
        auto += [f'{r[0].split("/", 2)[-1] if r[0].startswith("apps/") else r[0]:48s} {r[1]:5d} lines {r[2]:4d} KB' for r in items]
        auto += ['```']
    auto.append('<!-- AUTO:END -->')
    block = '\n'.join(auto)
    gp = os.path.join(ROOT, 'AI_GUIDE.md')
    g = open(gp, encoding='utf-8').read() if os.path.exists(gp) else '<!-- AUTO:START -->\n<!-- AUTO:END -->\n'
    g = re.sub(r'<!-- AUTO:START.*?<!-- AUTO:END -->', lambda m: block, g, flags=re.S)
    open(gp, 'w', encoding='utf-8').write(g)
    print('guide: %d symbols' % len(idx))
